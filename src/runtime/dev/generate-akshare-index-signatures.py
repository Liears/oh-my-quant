"""Snapshot whitelisted AKShare index function signatures for offline schema discovery."""

import argparse
import inspect
import json
import pathlib
import re
import sys


ROOT = pathlib.Path(__file__).resolve().parents[3]
ENDPOINTS_FILE = ROOT / "src/source/src/akshare-endpoints.ts"
OUTPUT_FILE = ROOT / "src/runtime/data/akshare-index-signatures.generated.ts"


def whitelisted_endpoints() -> list[str]:
    source = ENDPOINTS_FILE.read_text(encoding="utf-8")
    block = source.split("export const AKSHARE_PUBLIC_INDEX_ENDPOINTS = [", 1)[1].split("] as const;", 1)[0]
    names = re.findall(r'"([a-z][a-z0-9_]*)"', block)
    if not names or len(names) != len(set(names)):
        raise ValueError("AKShare index whitelist is empty or contains duplicates")
    return names


def parameter_type(parameter: inspect.Parameter) -> str:
    annotation = parameter.annotation
    default = parameter.default
    if annotation is str or annotation == "str" or isinstance(default, str):
        return "string"
    if annotation is bool or annotation == "bool" or isinstance(default, bool):
        return "boolean"
    if annotation is int or annotation == "int" or type(default) is int:
        return "integer"
    if annotation is float or annotation == "float" or type(default) is float:
        return "number"
    raise ValueError(f"Cannot represent AKShare parameter {parameter.name}: {parameter}")


def parameter_description(docstring: str, name: str) -> str:
    prefix = f":param {name}:"
    lines = docstring.splitlines()
    for index, line in enumerate(lines):
        if not line.startswith(prefix):
            continue
        parts = [line[len(prefix):].strip()]
        for following in lines[index + 1:]:
            if re.match(r"^\s*:[a-zA-Z][a-zA-Z0-9_]*(?:\s|:)", following):
                break
            if following.strip():
                parts.append(following.strip())
        return " ".join(" ".join(parts).split())[:512]
    return ""


def snapshot() -> tuple[str, dict[str, object]]:
    import akshare as ak

    signatures: dict[str, object] = {}
    for endpoint in whitelisted_endpoints():
        function = getattr(ak, endpoint, None)
        if not callable(function):
            raise ValueError(f"Whitelisted AKShare endpoint is unavailable: {endpoint}")
        parameters: dict[str, object] = {}
        for parameter in inspect.signature(function).parameters.values():
            if parameter.kind not in (inspect.Parameter.POSITIONAL_OR_KEYWORD, inspect.Parameter.KEYWORD_ONLY):
                raise ValueError(f"Cannot represent AKShare parameter kind: {endpoint}.{parameter.name}")
            spec: dict[str, object] = {"type": parameter_type(parameter), "required": parameter.default is inspect.Parameter.empty}
            if parameter.default is not inspect.Parameter.empty and parameter.default is not None:
                spec["default"] = parameter.default
            description = parameter_description(inspect.getdoc(function) or "", parameter.name)
            if description:
                spec["description"] = description
            parameters[parameter.name] = spec
        signatures[endpoint] = {"parameters": parameters}
    return str(getattr(ak, "__version__", "unknown")), signatures


def render(version: str, signatures: dict[str, object]) -> str:
    encoded = json.dumps(signatures, ensure_ascii=False, indent=2)
    return (
        "// Generated by src/runtime/dev/generate-akshare-index-signatures.py from local AKShare inspect.signature/docstrings.\n"
        "// Regenerate after changing the whitelist or installed AKShare version.\n"
        'import type { AksharePublicIndexEndpoint } from "../source/index.ts";\n\n'
        f"export const AKSHARE_INDEX_SIGNATURE_VERSION = {json.dumps(version)};\n"
        "export const AKSHARE_INDEX_SIGNATURES = " + encoded + " as const satisfies Record<AksharePublicIndexEndpoint, {\n"
        '  parameters: Record<string, { type: "string" | "number" | "integer" | "boolean"; required: boolean; default?: string | number | boolean; description?: string }>;\n'
        "}>;\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in snapshot differs from the installed AKShare signatures")
    args = parser.parse_args()
    version, signatures = snapshot()
    content = render(version, signatures)
    if args.check:
        if not OUTPUT_FILE.exists() or OUTPUT_FILE.read_text(encoding="utf-8") != content:
            print("AKShare index signature snapshot differs; regenerate it", file=sys.stderr)
            return 1
    else:
        OUTPUT_FILE.write_text(content, encoding="utf-8", newline="\n")
    print(f"AKShare {version}: {len(signatures)} whitelisted index signatures {'checked' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
